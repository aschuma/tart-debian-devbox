//! Layered `KEY=VALUE` env files → the `/etc/profile.d/tart-provision.sh`
//! payload, plus the "effective environment" view and secret masking.

use std::io::Read;
use std::path::{Path, PathBuf};

use serde::Serialize;

use crate::config::Config;
use crate::{Error, Result};

/// One `KEY=VALUE` entry with its origin.
#[derive(Debug, Clone, Serialize, PartialEq)]
pub struct EnvEntry {
    pub key: String,
    pub value: String,
    pub source: PathBuf,
}

/// Result of reading all configured env layers exactly once.
#[derive(Debug, Clone, Serialize)]
pub struct EnvLayers {
    /// Readable layers, in order.
    pub files: Vec<PathBuf>,
    /// Configured entries that were not readable.
    pub skipped: Vec<PathBuf>,
    /// Every entry of every layer, in file order (duplicates included).
    pub entries: Vec<EnvEntry>,
    /// Keys that were rejected because they are not valid shell identifiers.
    pub invalid_keys: Vec<String>,
    /// The raw list the files came from (for diagnostics).
    pub configured: Vec<String>,
}

impl EnvLayers {
    /// Resolves and reads the env files configured for `cfg`.
    pub fn load(cfg: &Config) -> Result<EnvLayers> {
        let mut layers = EnvLayers {
            files: vec![],
            skipped: vec![],
            entries: vec![],
            invalid_keys: vec![],
            configured: cfg.env_files.clone(),
        };
        for entry in &cfg.env_files {
            let Some(path) = cfg.resolve_env_path(entry) else {
                continue;
            };
            // Readability, not "is a regular file": FIFOs / secret-manager mounts must pass.
            match std::fs::File::open(&path) {
                Ok(mut f) if !path.is_dir() => {
                    let mut text = String::new();
                    f.read_to_string(&mut text)
                        .map_err(|e| Error::EnvRender(format!("{}: {e}", path.display())))?;
                    let (entries, invalid) = parse_env(&text, &path);
                    layers.entries.extend(entries);
                    layers.invalid_keys.extend(invalid);
                    layers.files.push(path);
                }
                _ => layers.skipped.push(path),
            }
        }
        Ok(layers)
    }

    /// Full content of the profile.d file (identical to what the bash tool produced).
    pub fn render(&self, generator: &str) -> String {
        let mut out = String::new();
        out.push_str("#!/usr/bin/env bash\n");
        out.push_str(&format!(
            "# Generated by {generator} provision — do not edit manually\n"
        ));
        out.push_str("# Later sections override earlier ones.\n");
        for file in &self.files {
            out.push('\n');
            out.push_str(&format!("# --- {} ---\n", file.display()));
            for e in self.entries.iter().filter(|e| &e.source == file) {
                out.push_str(&format!("export {}={}\n", e.key, shell_quote(&e.value)));
            }
        }
        out
    }

    /// Last definition of each key wins; order of first appearance.
    pub fn effective(&self) -> Vec<EnvEntry> {
        let mut out: Vec<EnvEntry> = Vec::new();
        for entry in &self.entries {
            match out.iter_mut().find(|e| e.key == entry.key) {
                Some(existing) => *existing = entry.clone(),
                None => out.push(entry.clone()),
            }
        }
        out
    }
}

/// Parses one env file. Returns entries and the invalid keys that were skipped.
pub fn parse_env(text: &str, source: &Path) -> (Vec<EnvEntry>, Vec<String>) {
    let mut entries = Vec::new();
    let mut invalid = Vec::new();
    for raw in text.lines() {
        let line = raw.trim_end_matches('\r').trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let line = line.strip_prefix("export ").unwrap_or(line);
        let (key, val) = line.split_once('=').unwrap_or((line, ""));
        let key: String = key.chars().filter(|c| !c.is_whitespace()).collect();
        let mut val = val.to_string();
        if (val.starts_with('"') && val.ends_with('"') && val.len() >= 2)
            || (val.starts_with('\'') && val.ends_with('\'') && val.len() >= 2)
        {
            val = val[1..val.len() - 1].to_string();
        }
        if !is_identifier(&key) {
            invalid.push(key);
            continue;
        }
        entries.push(EnvEntry {
            key,
            value: val,
            source: source.to_path_buf(),
        });
    }
    (entries, invalid)
}

pub fn is_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// Quotes like bash's `printf %q`.
pub fn shell_quote(s: &str) -> String {
    if s.is_empty() {
        return "''".to_string();
    }
    if s.chars().any(|c| c.is_ascii_control()) {
        let mut out = String::from("$'");
        for c in s.chars() {
            match c {
                '\n' => out.push_str("\\n"),
                '\t' => out.push_str("\\t"),
                '\r' => out.push_str("\\r"),
                '\'' => out.push_str("\\'"),
                '\\' => out.push_str("\\\\"),
                c if c.is_ascii_control() => out.push_str(&format!("\\{:03o}", c as u32)),
                c => out.push(c),
            }
        }
        out.push('\'');
        return out;
    }
    let mut out = String::with_capacity(s.len() * 2);
    for (i, c) in s.chars().enumerate() {
        let escape = match c {
            ' ' | '!' | '"' | '$' | '&' | '\'' | '(' | ')' | '*' | ',' | ';' | '<' | '>' | '?'
            | '[' | '\\' | ']' | '^' | '`' | '{' | '|' | '}' => true,
            '#' | '~' => i == 0,
            _ => false,
        };
        if escape {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// True if the key looks like it holds a secret.
pub fn is_secret_key(key: &str) -> bool {
    let k = key.to_ascii_uppercase();
    ["TOKEN", "SECRET", "PASS", "KEY", "CREDENTIAL", "AUTH"]
        .iter()
        .any(|p| k.contains(p))
}

pub const MASK: &str = "********";

/// Masks `export KEY=value` lines (optionally prefixed by a diff marker) whose key looks secret.
pub fn mask_rendered(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for line in text.split_inclusive('\n') {
        let (body, nl) = match line.strip_suffix('\n') {
            Some(b) => (b, "\n"),
            None => (line, ""),
        };
        let (prefix, rest) = match body.as_bytes().first() {
            Some(b'+' | b'-' | b' ') => (&body[..1], &body[1..]),
            _ => ("", body),
        };
        if let Some(kv) = rest.strip_prefix("export ") {
            if let Some((key, _)) = kv.split_once('=') {
                if is_identifier(key) && is_secret_key(key) {
                    out.push_str(prefix);
                    out.push_str(&format!("export {key}={MASK}"));
                    out.push_str(nl);
                    continue;
                }
            }
        }
        out.push_str(line);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quote_matches_bash_printf_q() {
        assert_eq!(shell_quote(""), "''");
        assert_eq!(shell_quote("two words"), "two\\ words");
        assert_eq!(shell_quote("has=equals"), "has=equals");
        assert_eq!(shell_quote("$HOME and `cmd`"), "\\$HOME\\ and\\ \\`cmd\\`");
        assert_eq!(shell_quote("a#b"), "a#b");
        assert_eq!(shell_quote("#b"), "\\#b");
        assert_eq!(shell_quote("~"), "\\~");
        assert_eq!(shell_quote("a~b"), "a~b");
        assert_eq!(shell_quote("a,b"), "a\\,b");
        assert_eq!(shell_quote("a\tb"), "$'a\\tb'");
        assert_eq!(shell_quote("ä"), "ä");
    }

    #[test]
    fn parse_handles_quotes_comments_crlf_export_invalid() {
        let src = PathBuf::from("/x/.env");
        let (e, bad) = parse_env(
            "A=1\n# c\n\nB=\"two words\"\nC='single'\nexport D=exported\r\nE=has=equals\n1BAD=nope\nF=$HOME\n",
            &src,
        );
        let kv: Vec<(&str, &str)> = e
            .iter()
            .map(|x| (x.key.as_str(), x.value.as_str()))
            .collect();
        assert_eq!(
            kv,
            vec![
                ("A", "1"),
                ("B", "two words"),
                ("C", "single"),
                ("D", "exported"),
                ("E", "has=equals"),
                ("F", "$HOME")
            ]
        );
        assert_eq!(bad, vec!["1BAD"]);
    }

    #[test]
    fn masking() {
        let s = "export API_TOKEN=abc\n+export DB_PASSWORD=x\n export PLAIN=1\n-export MY_KEY=k\n# --- f ---\n";
        assert_eq!(
            mask_rendered(s),
            "export API_TOKEN=********\n+export DB_PASSWORD=********\n export PLAIN=1\n-export MY_KEY=********\n# --- f ---\n"
        );
    }
}
